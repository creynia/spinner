// WP-L1 golden equivalence (layouts.md §7.3, §11): every chip-shaped preset stage lifted into an
// `x-chips` block and compiled back gives the same `layout` rows, and the run is byte-equal to the
// pinned golden trace. Also pins a chips x Martingale stage that scales every spot together.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { canonicalJson, definitionId } from '@core/experiment';
import { createInThreadTransport, createPool, simulate } from '@core/harness';
import type { SimPool } from '@core/harness';
import type { Json } from '@core/contracts/game';
import type { Stage, StrategyDefinition } from '@core/contracts/strategy';
import {
  compileChips,
  liftRows,
  normalizeStrategy,
  readStageChips,
  splitStageLayout,
  withStageChips,
} from '@core/strategy';
import {
  GOLDEN_BANKROLL,
  GOLDEN_SEED,
  PRESET_IDS,
  plugin,
  presetJson,
  rouletteDef,
} from './roulette-helpers';

const DIR = join(__dirname, '../../src/game/roulette/__fixtures__/golden');
const ROUNDS = 200;

interface Case {
  file: string;
  preset: string;
  rules: 'european' | 'american';
}
const CASES: Case[] = [
  ...PRESET_IDS.map((p) => ({ file: `${p}.european`, preset: p, rules: 'european' as const })),
  { file: 'martingale-red.american', preset: 'martingale-red', rules: 'american' },
  { file: 'james-bond.american', preset: 'james-bond', rules: 'american' },
];

/** The preset with every stage lifted into chips (layout rows regenerated by `withStageChips`). */
function lifted(preset: string): StrategyDefinition {
  const def = presetJson(preset) as StrategyDefinition;
  return {
    ...def,
    stages: def.stages.map((st: Stage) => {
      const chips = liftRows(st.layout ?? []);
      return chips ? withStageChips(st, chips) : st;
    }),
  };
}

let pool: SimPool;
beforeAll(() => {
  pool = createPool({
    size: 1,
    spawn: () => createInThreadTransport(plugin, { hop: 'microtask' }),
  });
});
afterAll(() => pool.terminate());

describe('every preset is chip-shaped', () => {
  it('has 12 presets', () => expect(PRESET_IDS).toHaveLength(12));

  for (const id of PRESET_IDS) {
    it(`${id}: lift then compile reproduces each stage's layout exactly`, () => {
      const def = presetJson(id) as StrategyDefinition;
      for (const st of def.stages) {
        const rows = st.layout ?? [];
        const chips = liftRows(rows);
        expect(chips, `${id}/${st.id} should lift`).not.toBeNull();
        expect(chips?.spots).toHaveLength(rows.length);
        expect(compileChips(chips!)).toEqual(rows);
        const next = withStageChips(st, chips);
        expect(next.layout).toEqual(rows);
        expect(splitStageLayout(next)).toMatchObject({ manual: [], stale: false });
        expect(readStageChips(next)).toEqual(chips);
      }
    });
  }

  it('James Bond lifts to 14 / 5 / 1 chips of one unit', () => {
    const bond = presetJson('james-bond') as StrategyDefinition;
    expect(liftRows(bond.stages[0]!.layout!)).toEqual({
      v: 1,
      chip: { units: 1 },
      spots: [
        { bet: 'high', chips: 14 },
        { bet: 'sixline:13-14-15-16-17-18', chips: 5 },
        { bet: 'straight:0', chips: 1 },
      ],
    });
  });

  it('red-mart-then-flat lifts each stage separately, to a progression and to units', () => {
    const d = presetJson('red-mart-then-flat') as StrategyDefinition;
    expect(liftRows(d.stages[0]!.layout!)?.chip).toEqual({ prog: 'm' });
    expect(liftRows(d.stages[1]!.layout!)?.chip).toEqual({ units: 1 });
  });
});

describe('golden-equivalence: chips-built presets replay the pinned traces', () => {
  for (const c of CASES) {
    it(`${c.file} is byte-equal to its golden trace`, async () => {
      const strategy = lifted(c.preset);
      for (const st of strategy.stages)
        expect((st as unknown as Record<string, unknown>)['x-chips']).toBeDefined();
      const def = rouletteDef(c.preset, { rules: c.rules, maxRounds: ROUNDS, strategy });
      const r = await simulate(pool, def, 0);
      const header = {
        golden: {
          preset: c.preset,
          rules: c.rules,
          seed: GOLDEN_SEED,
          session: 0,
          bankroll: GOLDEN_BANKROLL,
          maxRounds: ROUNDS,
          windows: r.trace.length,
          roundsPlayed: r.row.roundsPlayed,
          final: r.row.final,
          endedBy: r.row.endedBy,
        },
      };
      const out =
        [header, ...r.trace].map((w) => canonicalJson(w as unknown as Json)).join('\n') + '\n';
      expect(out).toBe(readFileSync(join(DIR, `${c.file}.seed${GOLDEN_SEED}.jsonl`), 'utf8'));
    });
  }
});

describe('definitions with x-chips', () => {
  it('normalizeStrategy keeps the block on the stage', () => {
    const d = normalizeStrategy(lifted('james-bond'));
    expect((d.stages[0] as unknown as Record<string, unknown>)['x-chips']).toEqual(
      readStageChips(lifted('james-bond').stages[0]),
    );
  });

  it('a chips version has its own definitionId; forgetting the chips restores the plain one', async () => {
    // The pinned flat-red vector itself is guarded by src/core/experiment/experiment.test.ts.
    const plain = await definitionId(rouletteDef('flat-red'));
    const withChips = lifted('flat-red');
    expect(await definitionId(rouletteDef('flat-red', { strategy: withChips }))).not.toBe(plain);
    const forgotten = {
      ...withChips,
      stages: withChips.stages.map((st) => ({ ...st, 'x-chips': undefined })),
    };
    const stripped = JSON.parse(JSON.stringify(forgotten)) as unknown;
    expect(await definitionId(rouletteDef('flat-red', { strategy: stripped }))).toBe(plain);
  });
});

describe('chips x Martingale doubles every spot together', () => {
  const strategy = {
    schema: 1,
    id: 'chips-mart',
    name: 'Chips with a Martingale',
    game: 'roulette',
    unit: 2500,
    progressions: {
      m: { kind: 'martingale', base: 500, maxSteps: 4, onCap: 'reset', track: 'round' },
    },
    stages: [
      withStageChips(
        { id: 'play', rules: [] },
        {
          v: 1,
          chip: { prog: 'm' },
          spots: [
            { bet: 'red', chips: 5 },
            { bet: 'dozen:1', chips: 5 },
            { bet: 'column:3', chips: 5 },
          ],
        },
      ),
    ],
  } as unknown as StrategyDefinition;

  it('compiles to chips x prog rows', () => {
    expect(strategy.stages[0]!.layout).toEqual([
      { bet: 'red', amount: { times: [5, { prog: 'm' }] } },
      { bet: 'dozen:1', amount: { times: [5, { prog: 'm' }] } },
      { bet: 'column:3', amount: { times: [5, { prog: 'm' }] } },
    ]);
  });

  it('scales all three spots by 2 after each losing spin and resets on a win', async () => {
    const def = rouletteDef('flat-red', { maxRounds: 60, strategy });
    const r = await simulate(pool, def, 0);
    const amounts = r.trace.map((w) => w.desired.map((d) => d.amount));
    // Every window: spots are 5 chips of the progression's current level, together.
    const levels = r.trace.map((w) => (w.prog.m as { amount: number }).amount);
    r.trace.forEach((w, i) => {
      expect(w.desired.map((d) => d.bet)).toEqual(['red', 'dozen:1', 'column:3']);
      expect(amounts[i]).toEqual([5 * levels[i]!, 5 * levels[i]!, 5 * levels[i]!]);
    });
    // The level doubles after a losing round (net < 0) and returns to base after a win.
    let doubled = 0;
    let reset = 0;
    for (let i = 1; i < r.trace.length; i++) {
      const prevNet = r.trace[i - 1]!.outcome?.net ?? 0;
      if (prevNet < 0 && levels[i - 1]! < 4000) {
        expect(levels[i]).toBe(levels[i - 1]! * 2);
        doubled++;
      } else if (prevNet > 0) {
        expect(levels[i]).toBe(500);
        reset++;
      }
    }
    expect(doubled).toBeGreaterThan(3);
    expect(reset).toBeGreaterThan(3);
    // Pin: the first windows of this seed.
    expect(levels.slice(0, 12)).toMatchInlineSnapshot(`
      [
        500,
        1000,
        2000,
        4000,
        500,
        1000,
        500,
        1000,
        500,
        500,
        1000,
        500,
      ]
    `);
  });
});
